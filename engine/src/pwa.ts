// The web export as an installable offline app (game.json "pwa": true; docs/design/mobile.md, step 6): the web manifest and the service
// worker. Pure: tools/export-web.mjs passes in what the export holds and writes the results next to index.html.

import type { StageSize } from './stage.js';

/** Whether game.json asks for the installable offline build (off unless `"pwa": true`: it caches the whole game on the player's device). */
export function pwaEnabled(game: unknown): boolean {
  return !!game && typeof game === 'object' && (game as { pwa?: unknown }).pwa === true;
}

/** What is wrong with game.json "pwa" (null when nothing). */
export function pwaProblem(raw: unknown): string | null {
  return raw === undefined || typeof raw === 'boolean' ? null : '"pwa" must be true or false';
}

/** The name under an app icon: whole words up to 12 characters (or the first 12 characters of one long word). */
function shortName(name: string): string {
  if (name.length <= 12) return name;
  const words = name.split(/\s+/);
  let out = '';
  for (const w of words) { if ((out ? `${out} ${w}` : w).length > 12) break; out = out ? `${out} ${w}` : w; }
  return out || name.slice(0, 12);
}

interface ManifestIcon { src: string; sizes: string; type: string; purpose?: string }

/** The web app manifest: the game's name, full screen in the stage's orientation, and its icon when it has one (a square PNG). */
export function webManifest(game: { title?: unknown; id?: unknown }, stage: StageSize, icon: { width: number; height: number } | null): string {
  const name = String(game.title ?? 'Untitled');
  const icons: ManifestIcon[] = icon && icon.width === icon.height
    ? [{ src: 'icon.png', sizes: `${icon.width}x${icon.height}`, type: 'image/png' }, { src: 'icon.png', sizes: `${icon.width}x${icon.height}`, type: 'image/png', purpose: 'maskable' }]
    : [];
  return JSON.stringify({
    name, short_name: shortName(name),
    start_url: './', scope: './', display: 'fullscreen', display_override: ['fullscreen', 'standalone'],
    orientation: stage.width >= stage.height ? 'landscape' : 'portrait', background_color: '#06080b', theme_color: '#06080b', icons,
  }, null, 2);
}

/**
 * The service worker: it keeps every file of the export (`files`, relative to index.html) in a cache named after `version`, answers
 * from the cache first (a `?v=` cache-buster does not matter: the version is the whole build) and from the network otherwise, and
 * removes the caches of older builds when it takes over. A new build has a new `version`, so it installs beside the old one and
 * replaces it at the next visit once every file is in.
 */
export function serviceWorkerSource(version: string, files: string[]): string {
  return `// Generated by the web export. Cache ${version}.
const CACHE = ${JSON.stringify(`vn-${version}`)};
const FILES = ${JSON.stringify(['./', ...files], null, 1)};
self.addEventListener('install', event => {
  event.waitUntil(caches.open(CACHE).then(cache => cache.addAll(FILES)).then(() => self.skipWaiting()));
});
self.addEventListener('activate', event => {
  event.waitUntil(caches.keys().then(keys => Promise.all(keys.filter(k => k.startsWith('vn-') && k !== CACHE).map(k => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener('fetch', event => {
  if (event.request.method !== 'GET') return;
  event.respondWith(caches.open(CACHE).then(async cache => (await cache.match(event.request, { ignoreSearch: true })) ?? fetch(event.request)));
});
`;
}
